"""Machine Learning Model Registry, Versioning, and Demand Prediction Models."""
from django.db import models
from decimal import Decimal
from apps.core.models import TimeStampedModel

class MLModelType(models.TextChoices):
    GUEST_DEMAND = 'GUEST_DEMAND', 'Daily Guest & Order Volume Forecaster'
    SALES_REVENUE = 'SALES_REVENUE', 'Gross Sales Revenue Forecaster'
    DISH_DEMAND = 'DISH_DEMAND', 'Culinary Dish Demand Predictor'
    INGREDIENT_REQUIREMENT = 'INGREDIENT_REQUIREMENT', 'Raw Material Procurement Predictor'

class PredictionModelRegistry(TimeStampedModel):
    """Registry of trained scikit-learn models with performance metrics and serialized artifacts."""
    model_name = models.CharField(max_length=100)
    model_type = models.CharField(max_length=30, choices=MLModelType.choices)
    version = models.CharField('Model Version', max_length=30, default='v1.0.0')
    algorithm = models.CharField('Algorithm', max_length=100, default='RandomForestRegressor')
    
    # Statistical performance scores
    r2_score = models.FloatField('R² Determination Score', default=0.0)
    mae_score = models.FloatField('Mean Absolute Error (MAE)', default=0.0)
    rmse_score = models.FloatField('Root Mean Squared Error (RMSE)', default=0.0)
    
    # Serialized weights file path
    artifact_path = models.CharField(max_length=255)
    training_sample_count = models.PositiveIntegerField(default=0)
    is_active = models.BooleanField(default=True)
    features_used = models.JSONField('Features Schema', default=list)

    class Meta:
        verbose_name = 'ML Model Registry'
        verbose_name_plural = 'ML Model Registries'
        ordering = ['-created_at']

    def __str__(self):
        return f"{self.model_name} {self.version} ({self.algorithm}) - R²: {self.r2_score:.2f}"

class DailyDemandForecast(TimeStampedModel):
    """Daily forecast predictions generated by active models."""
    branch = models.ForeignKey('branches.Branch', on_delete=models.CASCADE, related_name='demand_forecasts')
    target_date = models.DateField('Forecast Target Date', db_index=True)
    
    # Projected outputs
    predicted_order_count = models.PositiveIntegerField('Predicted Orders')
    predicted_guest_covers = models.PositiveIntegerField('Predicted Guest Covers')
    predicted_sales_revenue = models.DecimalField('Predicted Sales (₹)', max_digits=12, decimal_places=2)
    
    # Category / Dish projections
    predicted_biryani_servings = models.PositiveIntegerField('Predicted Biryani Servings', default=0)
    predicted_curry_servings = models.PositiveIntegerField('Predicted Curry Servings', default=0)
    predicted_starters_servings = models.PositiveIntegerField('Predicted Starters Servings', default=0)
    
    confidence_score = models.FloatField('Confidence Score (%)', default=88.5)
    model_used = models.ForeignKey(PredictionModelRegistry, on_delete=models.SET_NULL, null=True, related_name='forecasts')

    class Meta:
        verbose_name = 'Daily Demand Forecast'
        verbose_name_plural = 'Daily Demand Forecasts'
        unique_together = ('branch', 'target_date')
        ordering = ['target_date']

    def __str__(self):
        return f"Forecast for {self.target_date} ({self.branch.code}): {self.predicted_order_count} orders, ₹{self.predicted_sales_revenue}"

class IngredientRequirementForecast(TimeStampedModel):
    """Raw material procurement recommendations generated from forecasted dish consumption."""
    forecast = models.ForeignKey(DailyDemandForecast, on_delete=models.CASCADE, related_name='ingredient_requirements')
    ingredient = models.ForeignKey('inventory.Ingredient', on_delete=models.CASCADE, related_name='procurement_forecasts')
    predicted_quantity = models.DecimalField('Suggested Reorder Qty', max_digits=12, decimal_places=3)
    unit = models.CharField(max_length=20)
    estimated_cost = models.DecimalField('Est. Inward Cost (₹)', max_digits=10, decimal_places=2)

    class Meta:
        verbose_name = 'Ingredient Requirement Forecast'
        verbose_name_plural = 'Ingredient Requirement Forecasts'

    def __str__(self):
        return f"{self.predicted_quantity} {self.unit} of {self.ingredient.name} on {self.forecast.target_date}"
